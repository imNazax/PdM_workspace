/* Secuencia de tiempos de encendido en ms. El apagado dura lo mismo (duty 50%) */
const tick_t TIEMPOS[] = {500, 100, 100, 1000};

/* Cantidad de tiempos en la secuencia — se calcula automáticamente,
 * así no hay que actualizar este número si se modifica el arreglo */
#define CANT_TIEMPOS (sizeof(TIEMPOS) / sizeof(TIEMPOS[0]))

/* Índice del tiempo activo dentro de la secuencia */
uint8_t indiceTiempo = 0;

/* Estado actual del LED: true = encendido, false = apagado */
bool_t ledEncendido = false;

/* Estructura del temporizador no bloqueante */
